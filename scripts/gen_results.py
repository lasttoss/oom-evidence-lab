#!/usr/bin/env python3
"""Build docs/RESULTS.md from the real artifacts in out/. Every number is read from a file."""
from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out"
CASES = ["case1", "case2", "case3", "case4", "case5", "case6"]
TITLE = {
    "case1": "Heap OOM — objects retained by a static field",
    "case2": "Direct buffer OOM — exceeded MaxDirectMemorySize",
    "case3": "Metaspace OOM — ClassLoader leak",
    "case4": "Killed by the kernel — cgroup OOMKilled",
    "case5": "One allocation above the VM limit — not a leak",
    "case6": "Cannot create a native thread — pids.max, heap stays free",
}


def read(p: Path, default: str = "") -> str:
    return p.read_text(errors="replace").strip() if p.exists() else default


def kind_of(case: str) -> str:
    d = OUT / case
    if not d.is_dir():
        return "?"
    r = subprocess.run(["python3", str(ROOT / "scripts/classify.py"), str(d)],
                       capture_output=True, text=True)
    for line in r.stdout.splitlines():
        if line.startswith("01.kind"):
            return line.split(None, 1)[1].strip()
    return "?"


def main() -> None:
    lines = [
        "# Measured results",
        "",
        "Generated by `scripts/gen_results.py` from the artifacts in `out/`. "
        "Every number is read from a file — none is typed by hand.",
        "",
        "| Case | Kind | Exit | Main evidence |",
        "|---|---|---|---|",
    ]
    for c in CASES:
        d = OUT / c
        if not d.is_dir():
            lines.append(f"| {c} | not run | – | – |")
            continue
        msg = read(d / "oom_message.txt")
        killed = read(d / "oom_killed.txt")
        dump = read(d / "dump.txt")
        ev = msg or (f"OOMKilled={killed}" if killed else "")
        if dump:
            ev = f"{ev}; {dump}" if ev else dump
        lines.append(f"| {c} | {kind_of(c)} | {read(d / 'exit_code.txt', '?')} | {ev or 'see alert'} |")

    lines += ["", "## Raw evidence", ""]
    for c in CASES:
        d = OUT / c
        if not d.is_dir():
            continue
        stderr = read(d / "stderr.txt")
        stdout = read(d / "stdout.txt")
        lines += [
            f"### {c} — {TITLE[c]}",
            "```",
            f"exit_code:          {read(d / 'exit_code.txt', '?')}",
            f"stderr (line 1):    {stderr.splitlines()[0] if stderr else '(empty)'}",
            f"stdout (last line): {stdout.splitlines()[-1] if stdout else '(empty)'}",
        ]
        if (d / "oom_killed.txt").exists():
            lines.append(f"docker OOMKilled:   {read(d / 'oom_killed.txt')}")
        if (d / "dump.txt").exists():
            lines.append(read(d / "dump.txt"))
        lines += ["```", ""]

    lines += ["## Alert produced by the classifier", "",
              "This is an **unconfirmed hypothesis** by design: the alert carries evidence, "
              "the human makes the call.", "", "```"]
    r = subprocess.run(["python3", str(ROOT / "scripts/classify.py")], capture_output=True, text=True)
    lines += r.stdout.rstrip().splitlines()
    lines += ["```", ""]

    (ROOT / "docs/RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
