#!/usr/bin/env python3
"""Generate docs/ATTRIBUTION.md from classify.ATTRIBUTION — one table, one source of truth.

The question this answers: the alert already says WHICH family the failure belongs to.
Does it say WHERE the problem is? For some kinds, no — and the honest answer is to say so.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("classify", ROOT / "scripts/classify.py")
classify = importlib.util.module_from_spec(spec)
spec.loader.exec_module(classify)

LABEL = {
    "in-evidence": "**yes** — the artifact we already have names the site",
    "pre-captured": "**only if armed in advance** — the death itself leaves no site",
    "never": "**no** — nothing in the process can locate it",
}


def main() -> None:
    kinds = sorted(classify.CHECKS)
    rows = [(k, *classify.ATTRIBUTION.get(k, ("unknown", ""))) for k in kinds]
    counts = {}
    for _, loc, _ in rows:
        counts[loc] = counts.get(loc, 0) + 1

    lines = [
        "# Can the evidence say WHERE the problem is?",
        "",
        "Generated by `scripts/attribution.py` from `classify.ATTRIBUTION`. Classification answers *which",
        "family*; attribution answers *where*. They are different questions, and for some kinds the second",
        "one has no answer — saying so is part of the design.",
        "",
        f"in-evidence: **{counts.get('in-evidence', 0)}** · "
        f"pre-captured: **{counts.get('pre-captured', 0)}** · "
        f"never: **{counts.get('never', 0)}**",
        "",
        "| Kind | Location available | How to get it |",
        "|---|---|---|",
    ]
    for k, loc, how in rows:
        lines.append(f"| `{k}` | {LABEL.get(loc, loc)} | {how} |")

    lines += [
        "",
        "## The rule this table enforces",
        "",
        "**Classification happens after death; attribution has to be captured before it.**",
        "",
        "A SIGKILL leaves nothing behind: no frames, no dump, no `finally`. So for `container_kill` the only",
        "attribution that will ever exist is what `watch.sh` recorded while the process was alive — the growth",
        "curve and the cgroup `oom_kill` timestamp. If nobody armed that, the honest output is *\"the ceiling",
        "was hit; we cannot say which allocation drove it\"* — which is still more useful than a confident",
        "guess, because it tells the next person exactly what to arm.",
        "",
        "## What to arm, in order of value",
        "",
        "```",
        "1  interval snapshots (watch.sh)          the only attribution for a kernel kill",
        "2  -XX:+HeapDumpOnOutOfMemoryError        attribution for every Java-thrown kind",
        "3  -XX:NativeMemoryTracking=summary       off-heap and native, before the fact only",
        "4  JFR / async-profiler -e alloc          the allocation SITE, and only when armed",
        "5  core dump (ulimit -c + core_pattern)   native stack beyond hs_err",
        "```",
        "",
        "NMT cannot be switched on after the event, JFR cannot record the past, and a core dump is not",
        "written retroactively. That is why this lab has a `guard.sh` that fails the build when the flags are",
        "missing: the only moment to arm evidence is before the incident.",
    ]
    (ROOT / "docs/ATTRIBUTION.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:8]))
    print("wrote docs/ATTRIBUTION.md")


if __name__ == "__main__":
    main()
