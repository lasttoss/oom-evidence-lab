#!/usr/bin/env python3
"""Coverage report: for each OOM kind, is it covered by a rule, by a test, by a real reproduction?

Three coverage levels, and the difference matters more than the total:
  A  rule + test + a REAL reproduction in this repo   → someone has seen it die
  B  rule + test, never reproduced                    → the rule is read from the JDK, not from a crash
  C  no rule                                          → stored as `unknown` and queued for intake

Run: python3 scripts/coverage.py        (also writes docs/COVERAGE.md)
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


classify = load("classify", ROOT / "scripts/classify.py")
tests = load("test_classify", ROOT / "scripts/test_classify.py")

RULED = {k for k, _, _ in classify.RULES} | {"container_kill"}
TESTED = {expected for _, _, _, expected in tests.CASES}
REPRO = classify.REPRO


def has_artifacts(case: str) -> bool:
    d = ROOT / "out" / case
    return d.is_dir() and any(d.glob("exit_code.txt"))


def level(kind: str) -> str:
    ruled, tested = kind in RULED, kind in TESTED
    repro = kind in REPRO and has_artifacts(REPRO[kind])
    if ruled and tested and repro:
        return "A"
    if ruled and tested:
        return "B"
    return "C"


def main() -> None:
    kinds = sorted(RULED | TESTED | {"unknown"})
    rows = [(k, level(k), REPRO.get(k, "—")) for k in kinds]
    counts = {lv: sum(1 for _, x, _ in rows if x == lv) for lv in "ABC"}

    print(f"{'kind':<18} {'level':<6} {'repro'}")
    for k, lv, case in rows:
        print(f"{k:<18} {lv:<6} {case}")
    print(f"\nA={counts['A']}  B={counts['B']}  C={counts['C']}   "
          f"(A = reproduced in this repo, B = rule + test only, C = no rule)")

    doc = [
        "# Coverage",
        "",
        "Generated by `scripts/coverage.py`. Three levels, and the difference matters more than the total.",
        "",
        "| Level | Meaning |",
        "|---|---|",
        "| **A** | rule + synthetic test + a **real reproduction** in this repo |",
        "| **B** | rule + synthetic test, **never reproduced** — read from the JDK, not from a crash |",
        "| **C** | no rule — stored as `unknown`, queued for intake |",
        "",
        f"Totals: **A={counts['A']} · B={counts['B']} · C={counts['C']}**",
        "",
        "| Kind | Level | Repro case |",
        "|---|---|---|",
    ]
    doc += [f"| `{k}` | {lv} | {case} |" for k, lv, case in rows]
    doc += [
        "",
        "## Why a B is not a defect",
        "",
        "A rule taken from the JDK source is correct the day it is written; a reproduction only proves the",
        "shape of the evidence. `native_alloc` stays at B on purpose: breaking native allocation honestly",
        "needs a host condition (`vm.max_map_count`, an overcommitted kernel, a real malloc failure) that a",
        "container will not reproduce for you. Faking it would be worse than labelling it.",
        "",
        "## When a new kind appears — the intake path",
        "",
        "Nothing is guessed. An alert with `01.kind unknown` means the pipeline saw something it does not",
        "know, and the evidence is already stored. Then, in this order:",
        "",
        "1. `bash scripts/intake.sh <pid>` — collect the standard field set for that event into `out/intake/`,",
        "   plus the cgroup/kubelet facts and `dmesg`.",
        "   Then read field `11.why_unknown`: `NEW_SIGNATURE` means a new rule; `CONFIG_GAP` means the",
        "   evidence was never armed; `EVIDENCE_GAP` / `TIMING_GAP` mean the gap is collection, not knowledge.",
        "2. Add one rule line to `scripts/classify.py` (`RULES`) with the verbatim signature.",
        "3. Add its four ordered checks to `CHECKS` — a thread problem is not a heap problem.",
        "4. If it can be reproduced in a container, add a case; if not, leave `REPRO` without it and the",
        "   coverage table will honestly show B.",
        "5. Add one line to `scripts/test_classify.py`, then run `python3 scripts/test_classify.py` and",
        "   `python3 scripts/coverage.py`. The table is the proof that the gap closed.",
        "",
        "That is the whole mechanism: **unknown is a queue, not an error.**",
    ]
    (ROOT / "docs/COVERAGE.md").write_text("\n".join(doc) + "\n", encoding="utf-8")
    print("wrote docs/COVERAGE.md")


if __name__ == "__main__":
    main()
