#!/usr/bin/env python3
"""Unknown-signature queue: how many DISTINCT new signatures appeared, not how many events.

Fifty unknown events may be three signatures. The number that matters is
"new distinct signatures per month" — it must trend to zero as the rule table matures.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
INDEX = ROOT / "out" / "incidents" / "index.jsonl"


def load() -> list[dict]:
    if not INDEX.exists():
        return []
    return [json.loads(l) for l in INDEX.read_text(encoding="utf-8").splitlines() if l.strip()]


def sample_of(rec: dict) -> str:
    for name in ("stderr.txt", "stdout.txt"):
        p = ROOT / rec["bundle"] / name
        if p.exists():
            text = p.read_text(errors="replace").strip()
            if text:
                return text.splitlines()[0][:110]
    return "(no text)"


def main() -> None:
    rows = load()
    groups: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        groups[r.get("fp") or "-"].append(r)

    unknown = {fp: rs for fp, rs in groups.items() if any(r["kind"] == "unknown" for r in rs)}
    lines = [
        "# Unknown signatures",
        "",
        "Generated by `lab/report/gaps.py` from the incident index. Grouped by fingerprint, not by event:",
        "fifty unknown events may be three signatures.",
        "",
        f"Incidents stored: **{len(rows)}** · distinct signatures: **{len(groups)}** · "
        f"unknown signatures: **{len(unknown)}**",
        "",
    ]
    if not unknown:
        lines += ["No unknown signature recorded yet. That is not proof of completeness —",
                  "it means nothing outside the rule table has been captured so far.", ""]
    else:
        lines += ["| Fingerprint | Events | First seen | Last seen | Sample |", "|---|---|---|---|---|"]
        for fp, rs in sorted(unknown.items(), key=lambda kv: kv[1][0]["ts"]):
            rs.sort(key=lambda r: r["ts"])
            lines.append(f"| `{fp}` | {len(rs)} | {rs[0]['ts']} | {rs[-1]['ts']} | {sample_of(rs[-1])} |")
        lines += [
            "",
            "## For each fingerprint, decide once",
            "",
            "1. does it match one of the nine HotSpot messages after normalisation? → the rule is too narrow",
            "2. does it appear with `hs_err_pid` or a non-1 exit code? → native crash or startup failure, not a Java kind",
            "3. otherwise, after 2–3 occurrences, add one rule and four checks; a case only if reproducible",
            "",
            "Never write a rule from a single occurrence: a rule that fires wrongly is worse than `unknown`.",
            "",
        ]

    (ROOT / "docs/GAPS.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:6]))
    for fp, rs in sorted(unknown.items(), key=lambda kv: kv[1][0]["ts"]):
        print(f"  {fp}  events={len(rs)}  first={rs[0]['ts']}  {sample_of(rs[0])}")
    print("\nwrote docs/GAPS.md")


if __name__ == "__main__":
    main()
