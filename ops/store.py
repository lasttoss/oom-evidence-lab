#!/usr/bin/env python3
"""Persist every death as one evidence bundle with a searchable index.

Three storage tiers — tiers 1 and 2 must exist BEFORE the incident:
  1. BUNDLE    out/incidents/<UTC>-<case>/   raw artifacts (histo, gc.log, stderr, dump if kept)
  2. INDEX     out/incidents/index.jsonl     one line per incident — small, greppable, kept forever
  3. KNOWLEDGE docs/INCIDENTS.md             table generated from the index, for humans

Commands:
  store.py archive out/case1     copy artifacts into a new bundle, append index, rebuild the table
  store.py list                  print the index
  store.py prune --dumps-days N  delete heap dumps older than N days (text is never auto-deleted)
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import socket
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INC = ROOT / "out" / "incidents"
INDEX = INC / "index.jsonl"
DOC = ROOT / "docs" / "INCIDENTS.md"

# Heavy formats are prunable; text artifacts are kept forever.
HEAVY = (".hprof", ".jfr")


def signature_fp(bundle: Path) -> str | None:
    """Same fingerprint the alert uses, so an unknown can be counted across occurrences."""
    sys.path.insert(0, str(ROOT / "ops"))
    from signature import fingerprint
    for name in ("stderr.txt", "stdout.txt"):
        p = bundle / name
        if p.exists() and p.read_text(errors="replace").strip():
            return fingerprint(p.read_text(errors="replace"))
    return None


def classify_kind(case_dir: Path) -> str:
    r = subprocess.run([sys.executable, str(ROOT / "ops/classify.py"), str(case_dir)],
                       capture_output=True, text=True)
    for line in r.stdout.splitlines():
        if line.startswith("01.kind"):
            return line.split(None, 1)[1].strip()
    return "unknown"


def lab_commit() -> str:
    r = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                       capture_output=True, text=True)
    return r.stdout.strip() or "unknown"


def archive(case_dir_arg: str) -> Path:
    case_dir = (ROOT / case_dir_arg).resolve()
    if not case_dir.is_dir():
        raise SystemExit(f"no such directory: {case_dir}")

    kind = classify_kind(case_dir)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    bundle = INC / f"{stamp}-{case_dir.name}"
    bundle.mkdir(parents=True, exist_ok=True)   # safe when run twice within the same second

    for f in sorted(case_dir.rglob("*")):
        if f.is_file():
            target = bundle / f.relative_to(case_dir)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, target)

    stored, recorded = 0, 0
    for f in bundle.rglob("*"):
        if f.is_file() and f.suffix in HEAVY:
            stored += f.stat().st_size
    dump_txt = bundle / "dump.txt"
    if dump_txt.exists():
        m = re.search(r"(\d+)", dump_txt.read_text())
        recorded = int(m.group(1)) if m else 0

    record = {
        "ts": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "case": case_dir.name,
        "kind": kind,
        "exit_code": (bundle / "exit_code.txt").read_text().strip()
                        if (bundle / "exit_code.txt").exists() else None,
        "oom_killed": (bundle / "oom_killed.txt").read_text().strip()
                        if (bundle / "oom_killed.txt").exists() else None,
        "dump_bytes": stored,
        "dump_recorded_bytes": recorded,
        "bundle": str(bundle.relative_to(ROOT)),
        "host": socket.gethostname(),
        "lab_commit": lab_commit(),
        "fp": signature_fp(bundle),
        "files": sorted(str(f.relative_to(bundle)) for f in bundle.rglob("*") if f.is_file()),
    }
    INC.mkdir(parents=True, exist_ok=True)
    with INDEX.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(record, ensure_ascii=False) + "\n")

    (case_dir / "bundle.txt").write_text(record["bundle"] + "\n", encoding="utf-8")
    render_doc()
    print(f"bundle={record['bundle']}  kind={kind}  dump_stored={stored}  dump_recorded={recorded}")
    return bundle


def load() -> list[dict]:
    if not INDEX.exists():
        return []
    return [json.loads(l) for l in INDEX.read_text(encoding="utf-8").splitlines() if l.strip()]


def render_doc() -> None:
    rows = load()
    lines = [
        "# Incident log (generated)",
        "",
        "Generated by `ops/store.py` from `out/incidents/index.jsonl`. "
        "Every row is one real death of one process.",
        "",
        f"Total records: **{len(rows)}**",
        "",
        "| Timestamp (UTC) | Case | Kind | Exit | OOMKilled | Dump | Bundle |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        dump = f"{r['dump_recorded_bytes'] / 1024 / 1024:.0f} MB" if r.get("dump_recorded_bytes") else "–"
        lines.append(
            f"| {r['ts']} | {r['case']} | {r['kind']} | {r.get('exit_code') or '–'} | "
            f"{r.get('oom_killed') or '–'} | {dump} | `{r['bundle']}` |"
        )
    lines += [
        "",
        "## How to query",
        "",
        "```bash",
        "grep '\"kind\": \"heap\"' out/incidents/index.jsonl   # every heap OOM",
        "python3 ops/store.py list                      # everything",
        "python3 ops/store.py prune --dumps-days 30      # drop old dumps, keep text",
        "```",
        "",
        "## Retention rules",
        "",
        "- **Text is kept forever**: stderr, exit_code, histo, gc.log — tens of KB per incident.",
        "- **Dumps and JFR expire**: heavy, removed by `prune`.",
        "- **The index belongs in git**; dumps do not (ship them to object storage).",
    ]
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")


def prune(days: int) -> None:
    cutoff = datetime.now(timezone.utc).timestamp() - days * 86400
    removed = 0
    for f in INC.rglob("*"):
        if f.is_file() and f.suffix in HEAVY and f.stat().st_mtime < cutoff:
            f.unlink()
            removed += 1
    render_doc()
    print(f"removed {removed} heavy file(s) older than {days} days")


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("archive"); a.add_argument("case_dir")
    sub.add_parser("list")
    p = sub.add_parser("prune"); p.add_argument("--dumps-days", type=int, default=30)
    args = ap.parse_args()

    if args.cmd == "archive":
        archive(args.case_dir)
    elif args.cmd == "list":
        for r in load():
            print(json.dumps(r, ensure_ascii=False))
    else:
        prune(args.dumps_days)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
